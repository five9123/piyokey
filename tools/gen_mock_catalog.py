def romanize_korean(value: str) -> str:
    """Return a deterministic Revised-Romanization-style spelling guide."""
    result: list[str] = []
    for character in value:
        scalar = ord(character)
        if 0xAC00 <= scalar <= 0xD7A3:
            offset = scalar - 0xAC00
            initial = offset // 588
            vowel = (offset % 588) // 28
            final = offset % 28
            result.append(
                ROMANIZED_INITIALS[initial]
                + ROMANIZED_VOWELS[vowel]
                + ROMANIZED_FINALS[final]
            )
        else:
            result.append(COMPATIBILITY_JAMO_ROMANIZATION.get(character, character))
    return "".join(result)



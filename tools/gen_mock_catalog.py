COMPOUND_VOWEL_INDICES = {9, 10, 11, 14, 15, 16, 19}
COMPOUND_BATCHIM_INDICES = {3, 5, 6, 9, 10, 11, 12, 13, 14, 15, 18}
TENSE_INITIAL_INDICES = {1, 4, 8, 10, 13}


def typing_metrics(korean: str) -> tuple[int, int, int, int]:
    """Return a deterministic score based on the keys required to type a word."""
    syllable_count = len(korean)
    batchim_count = 0
    key_count = syllable_count * 2
    modifier_count = 0

    for character in korean:
        offset = ord(character) - 0xAC00
        initial_index = offset // 588
        vowel_index = (offset % 588) // 28
        batchim_index = offset % 28
        if batchim_index:
            batchim_count += 1
            key_count += 1
        if vowel_index in COMPOUND_VOWEL_INDICES:
            key_count += 1
            modifier_count += 1
        if batchim_index in COMPOUND_BATCHIM_INDICES:
            key_count += 1
            modifier_count += 2
        if initial_index in TENSE_INITIAL_INDICES:
            modifier_count += 1

    score = key_count * 3 + batchim_count * 2 + modifier_count
    return score, syllable_count, batchim_count, key_count



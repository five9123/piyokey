def build_hybrid_game_pools() -> dict[str, list[tuple[str, str, str]]]:
    """Build practical TOPIK tiers, then order and validate their typing load."""
    entry_by_word: dict[str, tuple[str, str, str]] = {}
    for pool in POOLS.values():
        for entry in pool:
            entry_by_word.setdefault(entry[0], entry)
    entry_by_word.update(HYBRID_EXTRA_ENTRIES)

    tiers: dict[str, list[tuple[str, str, str]]] = {}
    for level in ("beginner", "intermediate", "advanced"):
        semantic_candidates: dict[str, tuple[str, str, str]] = {}
        for game_mode in GAME_PRESET_MODES:
            for entry in POOLS[f"{game_mode}_topik_{level}"]:
                semantic_candidates.setdefault(entry[0], entry)

        exclusions = HYBRID_TIER_EXCLUSIONS[level]
        selected = [
            entry for word, entry in semantic_candidates.items()
            if word not in exclusions
        ]
        selected.extend(entry_by_word[word] for word in HYBRID_TIER_SUPPLEMENTS[level])
        selected = sorted(selected, key=lambda entry: (typing_metrics(entry[0]), entry[0]))

        words = {entry[0] for entry in selected}
        if len(selected) != GAME_PRESET_ITEM_COUNT or len(words) != GAME_PRESET_ITEM_COUNT:
            raise RuntimeError(
                f"hybrid {level} tier needs {GAME_PRESET_ITEM_COUNT} unique words, "
                f"got {len(selected)} entries / {len(words)} unique"
            )
        if not HYBRID_TIER_ANCHORS[level].issubset(words):
            missing = sorted(HYBRID_TIER_ANCHORS[level] - words)
            raise RuntimeError(f"hybrid {level} tier is missing practical anchors: {missing}")
        tiers[level] = selected

    word_sets = [{entry[0] for entry in tiers[level]} for level in tiers]
    if len(set().union(*word_sets)) != GAME_PRESET_ITEM_COUNT * len(tiers):
        raise RuntimeError("hybrid tiers must not repeat words across levels")

    profiles = {
        level: [typing_metrics(entry[0]) for entry in entries]
        for level, entries in tiers.items()
    }
    easy_counts = {
        level: sum(syllables <= 2 and batchim <= 1 for _, syllables, batchim, _ in metrics)
        for level, metrics in profiles.items()
    }
    hard_counts = {
        level: sum(syllables >= 3 or batchim >= 2 for _, syllables, batchim, _ in metrics)
        for level, metrics in profiles.items()
    }
    if easy_counts["beginner"] < 70:
        raise RuntimeError(f"beginner tier needs 70+ light words, got {easy_counts['beginner']}")
    if not hard_counts["beginner"] < hard_counts["intermediate"] < hard_counts["advanced"]:
        raise RuntimeError(f"hard-word quotas must increase: {hard_counts}")
    if hard_counts["advanced"] < 80:
        raise RuntimeError(f"advanced tier needs 80+ complex words, got {hard_counts['advanced']}")

    averages = [
        sum(metric[0] for metric in profiles[level]) / GAME_PRESET_ITEM_COUNT
        for level in ("beginner", "intermediate", "advanced")
    ]
    if not averages[0] < averages[1] < averages[2]:
        raise RuntimeError(f"hybrid typing difficulty averages must increase: {averages}")
    return tiers



def json_bytes(value: dict) -> bytes:
    return (json.dumps(value, ensure_ascii=False, indent=2) + "\n").encode("utf-8")


def load_deck_overrides(override_root: Path = DEFAULT_OVERRIDE_ROOT) -> dict[str, dict[str, dict]]:
    """Load full-deck overrides written by the local Deck Studio.

    The first key is the relative game-mode folder (or an empty string for
    catalog decks); the second is deck_id. Keeping authoring data outside this
    generator means operator edits survive deterministic fixture regeneration.
    """
    overrides: dict[str, dict[str, dict]] = {}
    if not override_root.exists():
        return overrides
    for path in sorted(override_root.rglob("*.json")):
        relative_parent = path.parent.relative_to(override_root).as_posix()
        folder = "" if relative_parent == "." else relative_parent
        if folder not in {"", *GAME_PRESET_SPECS.keys()}:
            raise RuntimeError(f"unsupported deck override folder: {folder}")
        try:
            deck = json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as error:
            raise RuntimeError(f"invalid deck override JSON: {path}: {error}") from error
        if not isinstance(deck, dict) or not isinstance(deck.get("deck_id"), str):
            raise RuntimeError(f"deck override must contain deck_id: {path}")
        if not isinstance(deck.get("version"), int) or deck["version"] < 1:
            raise RuntimeError(f"deck override must contain a positive version: {path}")
        if not isinstance(deck.get("items"), list) or not deck["items"]:
            raise RuntimeError(f"deck override must contain at least one item: {path}")
        oversized = [
            item.get("ko")
            for item in deck["items"]
            if len(item.get("ko", "")) > MAX_TARGET_CHARACTERS
        ]
        if oversized:
            raise RuntimeError(f"deck override target exceeds {MAX_TARGET_CHARACTERS} characters: {path}: {oversized}")
        bucket = overrides.setdefault(folder, {})
        if deck["deck_id"] in bucket:
            raise RuntimeError(f"duplicate deck override ID in {folder or 'catalog'}: {deck['deck_id']}")
        bucket[deck["deck_id"]] = deck
    return overrides


def apply_deck_overrides(decks: list[dict], overrides: dict[str, dict], folder: str) -> list[dict]:
    """Replace matching generated decks and append new authored decks."""
    result = copy.deepcopy(decks)
    positions = {deck["deck_id"]: index for index, deck in enumerate(result)}
    for deck_id, deck in overrides.items():
        if deck_id in positions:
            result[positions[deck_id]] = copy.deepcopy(deck)
        else:
            result.append(copy.deepcopy(deck))
    if len({deck["deck_id"] for deck in result}) != len(result):
        raise RuntimeError(f"duplicate deck ID after applying {folder or 'catalog'} overrides")
    return result


def generate(output: Path, seed: int) -> None:
    decks_dir = output / "decks"
    decks_dir.mkdir(parents=True, exist_ok=True)
    for old_file in decks_dir.glob("*.json"):
        old_file.unlink()

    generated_decks = [make_deck(spec, index, True) for index, spec in enumerate(OFFICIAL_SPECS, start=1)]
    if len(generated_decks) != 26 or not all(deck["official"] for deck in generated_decks):
        raise RuntimeError("fixture invariant failed: expected 26 official launch decks")
    deck_overrides = load_deck_overrides()
    decks = apply_deck_overrides(generated_decks, deck_overrides.get("", {}), "")
    decks = [enrich_deck_localizations(deck) for deck in decks]

    catalog_decks = []
    tag_counts: Counter[str] = Counter()
    for index, deck in enumerate(decks):
        file_name = f'{deck["deck_id"]}_v{deck["version"]}.json'
        payload = json_bytes(deck)
        (decks_dir / file_name).write_bytes(payload)
        total = 0
        recent = 0
        preview = [
            {
                "ko": item["ko"],
                "meaning_ja": item["meaning_ja"],
                "localizations": {
                    language_code: {"meaning": localization["meaning"]}
                    for language_code, localization in item["localizations"].items()
                },
            }
            for item in deck["items"][:10]
        ]
        catalog_decks.append({
            "deck_id": deck["deck_id"],
            "version": deck["version"],
            "name": deck["name"],
            "author_nickname": deck["author"]["nickname"],
            "official": deck["official"],
            "featured": index in {0, 5, 8, 9, 10},
            "type": deck["type"],
            "level": deck["level"],
            "tags": deck["tags"],
            "localizations": deck["localizations"],
            "item_count": len(deck["items"]),
            "size_bytes": len(payload),
            "downloads_total": total,
            "downloads_7d": recent,
            "created_at": deck["created_at"],
            "preview_items": preview,
            "file_url": f"decks/{file_name}",
        })
        tag_counts.update(deck["tags"])

    game_preset_decks = {}
    for directory, specs in GAME_PRESET_SPECS.items():
        preset_dir = decks_dir / directory
        preset_dir.mkdir(parents=True, exist_ok=True)
        for old_file in preset_dir.glob("*.json"):
            old_file.unlink()
        generated_preset_decks = [make_game_preset_deck(spec) for spec in specs]
        if len(generated_preset_decks) != 3 or not all(
            len(deck["items"]) == GAME_PRESET_ITEM_COUNT for deck in generated_preset_decks
        ):
            raise RuntimeError(
                f"fixture invariant failed: expected three {GAME_PRESET_ITEM_COUNT}-item "
                f"{directory} decks"
            )
        preset_decks = apply_deck_overrides(
            generated_preset_decks,
            deck_overrides.get(directory, {}),
            directory,
        )
        preset_decks = [enrich_deck_localizations(deck) for deck in preset_decks]
        for deck in preset_decks:
            file_name = f'{deck["deck_id"]}_v{deck["version"]}.json'
            (preset_dir / file_name).write_bytes(json_bytes(deck))
        game_preset_decks[directory] = preset_decks

    catalog = {
        "catalog_version": BASE_CATALOG_VERSION,
        "generated_at": GENERATED_AT,
        "decks": catalog_decks,
        "tags": [
            {
                "tag": tag,
                "deck_count": count,
                "category": tag_category(tag),
                "localizations": load_content_localizations()[1]["tags"][tag],
            }
            for tag, count in sorted(tag_counts.items(), key=lambda item: (-item[1], item[0].casefold()))
        ],
    }
    output.mkdir(parents=True, exist_ok=True)
    (output / "catalog.json").write_bytes(json_bytes(catalog))

    updates_dir = output / "updates"
    update_decks_dir = updates_dir / "decks"
    update_decks_dir.mkdir(parents=True, exist_ok=True)
    for old_file in update_decks_dir.glob("*.json"):
        old_file.unlink()

    updated_decks = copy.deepcopy(decks)
    updated_deck = next(deck for deck in updated_decks if deck["deck_id"] == UPDATE_DECK_ID)
    updated_deck["version"] = max(BASE_DECK_VERSION + 1, updated_deck["version"] + 1)
    updated_deck["updated_at"] = UPDATE_GENERATED_AT
    if not any(item["ko"] == "약속" for item in updated_deck["items"]):
        used_item_ids = {item["id"] for item in updated_deck["items"]}
        next_item_number = len(updated_deck["items"]) + 1
        while f"i_{next_item_number:03d}" in used_item_ids:
            next_item_number += 1
        updated_deck["items"].append({
            "id": f"i_{next_item_number:03d}",
            "ko": "약속",
            "reading_ja": "ヤクソク",
            "meaning_ja": "約束",
            "localizations": localized_item_fields("약속", "約束"),
            "audio": audio_asset_path("약속"),
        })

    updated_catalog = copy.deepcopy(catalog)
    updated_catalog["catalog_version"] = BASE_CATALOG_VERSION + 1
    updated_catalog["generated_at"] = UPDATE_GENERATED_AT
    entries_by_id = {entry["deck_id"]: entry for entry in updated_catalog["decks"]}
    for deck in updated_decks:
        file_name = f'{deck["deck_id"]}_v{deck["version"]}.json'
        payload = json_bytes(deck)
        (update_decks_dir / file_name).write_bytes(payload)
        entry = entries_by_id[deck["deck_id"]]
        entry["version"] = deck["version"]
        entry["item_count"] = len(deck["items"])
        entry["size_bytes"] = len(payload)
        entry["preview_items"] = [
            {
                "ko": item["ko"],
                "meaning_ja": item["meaning_ja"],
                "localizations": {
                    language_code: {"meaning": localization["meaning"]}
                    for language_code, localization in item["localizations"].items()
                },
            }
            for item in deck["items"][:10]
        ]
        entry["file_url"] = f"decks/{file_name}"
    updates_dir.mkdir(parents=True, exist_ok=True)
    (updates_dir / "catalog.json").write_bytes(json_bytes(updated_catalog))

    print(
        f"wrote {output}/catalog.json and {len(decks)} deck files "
        f"plus {sum(len(decks) for decks in game_preset_decks.values())} game preset decks "
        f"and catalog v{BASE_CATALOG_VERSION + 1} "
        f"update fixture for {UPDATE_DECK_ID}"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED)
    args = parser.parse_args()
    generate(args.output.resolve(), args.seed)


if __name__ == "__main__":
    main()

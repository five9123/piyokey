def iso_date(day_offset: int) -> str:
    start = datetime(2026, 1, 1, tzinfo=timezone.utc)
    return (start + timedelta(days=day_offset)).strftime("%Y-%m-%dT%H:%M:%SZ")


def select_items(pool_name: str, offset: int, count: int) -> list[dict]:
    pool = POOLS[pool_name]
    selected = [pool[(offset + index) % len(pool)] for index in range(count)]
    oversized = [ko for ko, _, _ in selected if len(ko) > MAX_TARGET_CHARACTERS]
    if oversized:
        raise RuntimeError(
            f"target exceeds {MAX_TARGET_CHARACTERS} characters in {pool_name}: {oversized}"
        )
    if pool_name in ENRICHMENT_POOLS:
        syllable_counts = [sum("가" <= character <= "힣" for character in ko) for ko, _, _ in selected]
        invalid = [ko for (ko, _, _), length in zip(selected, syllable_counts) if not 2 <= length <= 8]
        if invalid:
            raise RuntimeError(f"target must contain 2...8 Hangul syllables in {pool_name}: {invalid}")
        if count < 10 or len(set(syllable_counts)) < 4:
            raise RuntimeError(f"enrichment deck lacks length variety in {pool_name}: {syllable_counts}")
        if not any(" " in ko for ko, _, _ in selected) or not any(" " not in ko for ko, _, _ in selected):
            raise RuntimeError(f"enrichment deck must mix words and phrases in {pool_name}")
    return [
        {
            "id": f"i_{index:03d}",
            "ko": ko,
            "reading_ja": reading,
            "meaning_ja": meaning,
            "audio": audio_asset_path(ko),
        }
        for index, (ko, reading, meaning) in enumerate(selected, start=1)
    ]


